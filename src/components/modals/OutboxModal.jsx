import React, { useState } from 'react';
import { useApp } from '../../context/AppContext';
import { BASE_DATE, getDateString } from '../../constants/initialData';

export function OutboxModal({ onClose }) {
  const { data, setSession } = useApp();
  const { mail } = data;
  const [filter, setFilter] = useState('all');

  const handleLinkAction = (action, dest) => {
    onClose();
    if (action === 'setpw') {
      setSession({ role: 'setpw', who: dest, pid: null });
      return;
    }
    const [role, idOrEmail] = dest.split('|');
    if (role === 'author') {
      setSession({ role: 'author', who: idOrEmail, pid: null });
    } else if (role === 'editor') {
      setSession({ role: 'editor', who: idOrEmail, pid: null, tab: 'dash' });
    } else if (role === 'reviewer') {
      setSession({ role: 'reviewer', who: idOrEmail, pid: null });
    } else if (role === 'public') {
      setSession({ role: 'public', pid: idOrEmail });
    }
  };

  const filteredMail = mail.filter((m) => {
    if (filter === 'email') return m.kind === 'Email';
    if (filter === 'sms') return m.kind === 'SMS';
    return true;
  });

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between border-b border-[#e5ecf6] pb-3">
        <div>
          <h2 className="text-xl font-bold text-[#0d3b6e]">
            Outbox: System Communications
          </h2>
          <p className="text-xs text-[#55657d] mt-0.5">
            All simulated emails, SMS alerts, and one-click action links generated by the workflow.
          </p>
        </div>
        <button
          onClick={onClose}
          className="px-3 py-1 text-sm bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-md font-medium transition-colors"
        >
          Close
        </button>
      </div>

      <div className="flex items-center gap-2 border-b border-slate-100 pb-2">
        <button
          onClick={() => setFilter('all')}
          className={`px-3 py-1 rounded text-xs font-semibold ${
            filter === 'all'
              ? 'bg-[#0d3b6e] text-white'
              : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
          }`}
        >
          All ({mail.length})
        </button>
        <button
          onClick={() => setFilter('email')}
          className={`px-3 py-1 rounded text-xs font-semibold ${
            filter === 'email'
              ? 'bg-[#0d3b6e] text-white'
              : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
          }`}
        >
          Emails ({mail.filter((m) => m.kind === 'Email').length})
        </button>
        <button
          onClick={() => setFilter('sms')}
          className={`px-3 py-1 rounded text-xs font-semibold ${
            filter === 'sms'
              ? 'bg-[#0d3b6e] text-white'
              : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
          }`}
        >
          SMS Alerts ({mail.filter((m) => m.kind === 'SMS').length})
        </button>
      </div>

      <div className="max-h-[65vh] overflow-y-auto space-y-3 pr-1">
        {filteredMail.length === 0 ? (
          <p className="text-center py-8 text-sm text-[#55657d]">No communications recorded yet.</p>
        ) : (
          filteredMail.map((item) => (
            <div
              key={item.n}
              className="bg-[#f8fafc] border border-[#d5deeb] rounded-xl p-4 text-sm space-y-2 hover:border-blue-300 transition-colors shadow-2xs"
            >
              <div className="flex items-center justify-between text-xs text-[#55657d] flex-wrap gap-1">
                <span className="font-mono">
                  {getDateString(BASE_DATE, item.day)} at {item.time}
                </span>
                <div className="flex items-center gap-2">
                  <span
                    className={`px-2 py-0.5 rounded text-[11px] font-bold ${
                      item.kind === 'SMS'
                        ? 'bg-amber-100 text-amber-800'
                        : 'bg-blue-100 text-blue-800'
                    }`}
                  >
                    {item.kind}
                  </span>
                  <span>
                    To: <b className="text-slate-900">{item.to}</b>
                  </span>
                </div>
              </div>

              <div className="font-semibold text-slate-900">{item.subject}</div>

              <pre className="text-xs bg-white border border-slate-200 p-3 rounded-lg text-slate-700 whitespace-pre-wrap font-sans leading-relaxed">
                {item.body}
              </pre>

              {item.links && item.links.length > 0 && (
                <div className="flex gap-2 pt-1 flex-wrap">
                  {item.links.map((link, idx) => (
                    <button
                      key={idx}
                      onClick={() => handleLinkAction(link.a, link.d)}
                      className="px-3 py-1 bg-[#0d3b6e] hover:bg-[#0a2d54] text-white text-xs font-medium rounded-md shadow-2xs transition-colors flex items-center gap-1.5"
                    >
                      <span>→</span> {link.l}
                    </button>
                  ))}
                </div>
              )}
            </div>
          ))
        )}
      </div>
    </div>
  );
}
